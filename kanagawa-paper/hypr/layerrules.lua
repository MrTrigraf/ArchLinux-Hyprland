-- ─────────────────────────────────────────────────────────────────────────────
-- layerrules.lua — правила для layer-shell поверхностей (бар, нотификации,
-- обои и т.п.). Это НЕ окна, а слои поверх/под обычными окнами.
--
-- Параметры blur наследуются из decoration.blur в visual.lua темы.
-- Здесь только указываем «применить blur к слою с таким namespace».
-- ─────────────────────────────────────────────────────────────────────────────

-- ── Quickshell bar (namespace: "qs-bar") ────────────────────────────────────
-- Размытие фона под прозрачным баром.
-- ignore_alpha = 0.5 → blur применяется к участкам с alpha ≤ 0.5.
-- Наш Theme.background имеет alpha 0.72 (более непрозрачный), поэтому
-- blur «не пробивает» сквозь сам фон бара — рисуется под ним аккуратно.
hl.layer_rule({
    match = { namespace = "qs-bar" },
    blur = true,
    ignore_alpha = 0.7,
})
